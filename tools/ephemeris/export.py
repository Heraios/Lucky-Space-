import json,sys
d=json.load(open('states.json'))
f=lambda x:float('%.11g'%x)
out={'step_mars':20.0,'step_pluto':400.0,'t0':d['mars'][0][0],
     'mu_mars':d['mu_mars'],'mu_pluto':d['mu_pluto'],
     'mars':[[f(x) for x in e[1:]] for e in d['mars']],
     'pluto':[[f(x) for x in e[1:]] for e in d['pluto']],
     'pole':[[f(x) for x in e[1:]] for e in d['pole']]}
assert abs(d['pluto'][1][0]-d['pluto'][0][0]-400)<1e-6 and abs(d['mars'][1][0]-d['mars'][0][0]-20)<1e-6
s=json.dumps(out,separators=(',',':'))
open(sys.argv[1],'w').write("/* Heliocentric J2000-ecliptic state vectors (AU, AU/day) for Mars and the Pluto system barycentre,\n   plus Mars's spin-axis direction, for AD 15995-16106 (TDB).\n   Generated by tools/ephemeris/run.py from JPL DE421 initial conditions + N-body integration. */\nwindow.EPH="+s+";\n")
print(len(s))
